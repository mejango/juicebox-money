import { expect, test } from '@playwright/test'

for (const width of [390, 1280]) {
  test(`Defifa NFT inventory separates native actions from generic controls at ${width}px`, async ({ page, context }) => {
    await page.setViewportSize({ width, height: 900 })
    await context.route(/^https?:\/\//, async route => {
      const url = new URL(route.request().url())
      if (['127.0.0.1', 'localhost'].includes(url.hostname)) return route.continue()
      await route.fulfill({ status: 503, body: '{}' })
    })
    const errors: string[] = []
    const curveRequests: string[] = []
    page.on('request', request => { if (request.url().startsWith('https://metalog.money/')) curveRequests.push(request.url()) })
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/defifa-inventory-proof')
    await expect(page.locator('[data-defifa-ready="true"]')).toBeVisible()
    for (const name of ['NFT inventory']) {
      const surface = page.getByRole('region', { name, exact: true })
      await expect(surface.getByRole('row')).toHaveCount(8)
      await expect(surface).toContainText('Home team')
      await expect(surface).toContainText('Away team')
      await expect(surface).toContainText('2.75 USDC')
      await expect(surface).toContainText('Protocol phase: Complete')
      await expect(surface).toContainText('1.25 USDC')
      await expect(surface.locator('a[href^="https://metalog.money"]')).toHaveCount(0)
      await expect(surface.getByRole('columnheader', { name: 'Tier', exact: true })).toBeVisible()
      await expect(surface.getByRole('columnheader', { name: 'Name', exact: true })).toBeVisible()
      await expect(surface.getByRole('columnheader', { name: 'Current supply', exact: true })).toBeVisible()
      await expect(surface.getByRole('columnheader', { name: 'Price', exact: true })).toBeVisible()
      await expect(surface).not.toContainText('Metalog')
      await expect(surface.getByRole('tab')).toHaveCount(0)
      await expect(surface.getByRole('img')).toHaveCount(0)
      await expect(surface).not.toContainText('curve')
      await expect(surface).not.toContainText('·')
      await expect(surface.getByRole('button')).toHaveCount(1)
      if (name === 'Payment surface') await expect(surface.getByRole('button', { name: 'Add to balance', exact: true })).toBeEnabled()
      else await expect(surface.getByRole('button', { name: 'Connect wallet', exact: true })).toBeEnabled()
      await expect(surface.getByRole('spinbutton')).toHaveCount(0)
      await expect(surface).not.toContainText('Unlimited')
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const checkout = page.getByRole('region', { name: 'Payment surface', exact: true })
    await expect(checkout.locator('table')).toHaveCount(0)
    await expect(checkout).toContainText('Shop')
    await expect(checkout).toContainText('Protocol phase: Complete')
    await expect(checkout.locator('[data-nft-checkout-tier] img')).toHaveCount(7)
    await expect(checkout.getByRole('button', { name: 'Add to balance', exact: true })).toBeEnabled()
    await expect(checkout.locator('a[href^="https://metalog.money"]')).toHaveCount(0)
    await expect(checkout).not.toContainText('Cosmetic name')
    expect(errors).toEqual([])
    expect(curveRequests).toEqual([])
    await page.screenshot({ path: `test-results/defifa-inventory-${width}.png`, fullPage: true })
  })

  test(`Defifa mint phase offers native tier quantities at ${width}px`, async ({ page, context }) => {
    await page.setViewportSize({ width, height: 900 })
    await context.route(/^https?:\/\//, async route => {
      const url = new URL(route.request().url())
      if (['127.0.0.1', 'localhost'].includes(url.hostname)) return route.continue()
      await route.fulfill({ status: 503, body: '{}' })
    })
    await page.goto('/defifa-inventory-proof?phase=mint')
    const surface = page.getByRole('region', { name: 'Payment surface', exact: true })
    await expect(surface.locator('[data-nft-checkout-tier]')).toHaveCount(7)
    await expect(surface.locator('[data-nft-checkout-tier] img')).toHaveCount(7)
    const firstCard = surface.locator('[data-nft-checkout-tier="1"]')
    await expect(firstCard.getByRole('img', { name: 'Home team', exact: true })).toBeVisible()
    await expect(firstCard.getByRole('button', { name: '1.25 USDC', exact: true })).toBeVisible()
    await firstCard.getByRole('button', { name: 'Home team', exact: true }).click()
    await expect(firstCard.getByRole('button', { name: 'Add one Home team', exact: true })).toBeVisible()
    await expect(firstCard.getByRole('group', { name: 'Home team quantity', exact: true })).toContainText('1')
    const amount = surface.getByRole('textbox', { name: 'NFT amount', exact: true })
    await expect(amount).toHaveValue('1.25')
    await expect(amount).toHaveAttribute('readonly', '')
    await surface.locator('[data-nft-checkout-tier="2"]').getByRole('button', { name: 'Away team', exact: true }).click()
    await expect(amount).toHaveValue('4')
    const summary = surface.locator('[aria-label="Selected NFTs"]')
    await expect(summary).toContainText('Home team')
    await expect(summary).toContainText('Away team')
    await expect(summary).toContainText('2 NFTs')
    await expect(summary).toContainText('4 USDC')
    await expect(surface).not.toContainText('Cosmetic name')
    await expect(surface.getByRole('button', { name: 'Connect wallet', exact: true })).toBeEnabled()
    await expect(surface.getByRole('button', { name: 'Add to balance', exact: true })).toBeEnabled()
    await expect(surface).not.toContainText('Metalog')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/defifa-native-mint-${width}.png`, fullPage: true })
  })
}

for (const width of [390, 1280]) {
  for (const presentation of ['ordinary', 'native']) {
    test(`${presentation} checkout shows named fallback for invalid SVG at ${width}px`, async ({ page, context }) => {
      await page.setViewportSize({ width, height: 900 })
      await context.route(/^https?:\/\//, async route => {
        const url = new URL(route.request().url())
        // This cosmetic fixture seeds inventory and does not prove protocol reads.
        // Keep its deliberately unavailable RPC out of the real-reader fixture audit.
        if (url.pathname.startsWith('/rpc/')) return route.fulfill({ status: 503, body: '{}' })
        if (['127.0.0.1', 'localhost'].includes(url.hostname)) return route.continue()
        await route.fulfill({ status: 503, body: '{}' })
      })
      await page.goto(`/defifa-inventory-proof?phase=mint&media=invalid&presentation=${presentation}`)
      const surface = page.getByRole('region', { name: 'Payment surface', exact: true })
      const card = surface.locator('[data-nft-checkout-tier="2"]')
      await expect(card).toContainText('Away team')
      await expect(card.locator('img')).toHaveCount(0)
      await card.getByRole('button', { name: 'Away team', exact: true }).click()
      await expect(card.getByRole('group', { name: 'Away team quantity', exact: true })).toContainText('1')
      await expect(surface.locator('[data-nft-checkout-tier="1"]')).toContainText('Home team')
      await expect(surface.locator('img')).toHaveCount(0)
      await expect(surface).toContainText('Away team')
      if (presentation === 'native') await expect(surface.getByRole('textbox', { name: 'NFT amount', exact: true })).toHaveValue('2.75')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({ path: `test-results/${presentation}-checkout-invalid-svg-${width}.png`, fullPage: true })
    })
  }
}
